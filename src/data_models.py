from pydantic import BaseModel, Field, model_validator
import uuid
from typing import Self


class MinimalSource(BaseModel):
    """Single source of information: a slice of a file of the corpus.

    Used both by the reference datasets (expected sources) and by our
    retriever (found sources / chunks of the index).

    Attributes:
        file_path: path relative to the project root, written exactly as
            in the corpus (e.g. "data/raw/vllm-0.10.1/..."). Compared
            verbatim by the moulinette.
        first_character_index: start of the slice in the file (included).
        last_character_index: end of the slice in the file (excluded),
            so that text == file_content[first:last].
        text: content of the slice. Optional: filled by the indexer,
            but empty ("") in the sources of the reference datasets.

    Validation:
        first_character_index <= last_character_index, and if text is set,
        len(text) == last_character_index - first_character_index.
    """
    file_path: str
    first_character_index: int
    last_character_index: int
    text: str = ""

    @model_validator(mode="after")
    def check_range(self) -> Self:
        first = self.first_character_index
        last = self.last_character_index
        if not first <= last:
            raise ValueError(
                f"The first index is superior to the last in {self!r}")
        if self.text and last - first != len(self.text):
            raise ValueError(
                f"The length of the text does not correspond in {self!r}")
        return self


class UnansweredQuestion(BaseModel):
    """Question of a dataset, without its expected answer.

    Found in data/datasets/UnansweredQuestions/ (input of search_dataset).

    Attributes:
        question_id: unique id of the question (a uuid4 is generated if
            missing). Used to match our results with the reference.
        question: text of the question.
    """
    question_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    question: str


class AnsweredQuestion(UnansweredQuestion):
    """Question of a dataset with its expected answer (ground truth).

    Found in data/datasets/AnsweredQuestions/. Read only: we never produce
    it, the moulinette compares our results against it (recall@k).

    Attributes:
        question_id: unique id of the question (inherited).
        question: text of the question (inherited).
        sources: the CORRECT sources, that the retriever should find.
        answer: the reference answer, written by a human.
    """
    sources: list[MinimalSource]
    answer: str


class RagDataset(BaseModel):
    """A dataset of questions, as stored in data/datasets/*/*.json.

    Input of search_dataset (via load_questions).

    Attributes:
        rag_questions: the questions, answered (AnsweredQuestions/ files)
            or not (UnansweredQuestions/ files).
    """
    rag_questions: list[AnsweredQuestion | UnansweredQuestion]


class MinimalSearchResults(BaseModel):
    """What our retriever found for one question.

    Built by search_questions, one per question of the dataset.

    Attributes:
        question_id: id of the question, copied from the dataset.
        question: text of the question, copied from the dataset.
        retrieved_sources: the top-k chunks FOUND by the retriever, best
            first. Compared to AnsweredQuestion.sources for the recall.
    """
    question_id: str
    question: str
    retrieved_sources: list[MinimalSource]


class MinimalAnswer(MinimalSearchResults):
    """What our retriever found for one question + the LLM answer.

    Built by answer_gen from a MinimalSearchResults.

    Attributes:
        question_id: id of the question (inherited).
        question: text of the question (inherited).
        retrieved_sources: the top-k chunks found by the retriever,
            used as context for the LLM (inherited).
        answer: answer GENERATED by Qwen from retrieved_sources.
    """
    answer: str


class StudentSearchResults(BaseModel):
    """Output file of search_dataset.

    Saved in data/output/search_results/<DatasetScope>/, and given as
    first argument to the moulinette (evaluate_student_search_results)
    and as input of answer_dataset.

    Attributes:
        search_results: one MinimalSearchResults per question
            (question_id, question, retrieved_sources).
        k: number of sources requested per question.
    """
    search_results: list[MinimalSearchResults]
    k: int


class StudentSearchResultsAndAnswer(BaseModel):
    """Output file of answer_dataset.

    Saved in data/output/search_results_and_answer/<DatasetScope>/.

    Attributes:
        search_results: one MinimalAnswer per question
            (question_id, question, retrieved_sources, answer).
        k: number of sources requested per question.
    """
    search_results: list[MinimalAnswer]
    k: int
